#!/usr/bin/env python3
"""Install the local add-on, preserving existing app and agent configuration."""

import argparse
import json
import os
import shlex
import shutil
import subprocess
import sys
import tempfile
from datetime import datetime
from pathlib import Path

from app_ui import apply_app_ui, plan_app_ui
from core import APP_HOME, HOME, STATE, Error, read_json, save_json

PROJECT = Path(__file__).resolve().parent
CONFIG = Path(os.environ.get("XDG_CONFIG_HOME", HOME / ".config"))
PI_HOME = Path(os.environ.get("PI_CODING_AGENT_DIR", HOME / ".pi/agent"))
CODEX_HOME = Path(os.environ.get("CODEX_HOME", HOME / ".codex"))
COMMAND = HOME / ".local/bin/herdr-hibernate"
SERVICE = CONFIG / "systemd/user/herdr-app-hibernate.service"
LEGACY_PROJECT = HOME / "Code/herdr-app-hibernate"


def entrypoint_files(command=COMMAND, extension=PI_HOME / "extensions/herdr-app-hibernate.ts"):
    launcher_target = os.path.relpath(PROJECT / "herdr-hibernate", command.parent)
    # Keep this a Python file: the existing systemd unit runs it with Python,
    # while the CLI, desktop mods, and Codex hook execute it directly.
    launcher = f'''#!/usr/bin/env python3
# Generated by the Herdr App hibernation installer.
import os
import sys
from pathlib import Path

helper = Path(__file__).resolve().parent / {launcher_target!r}
os.execv(sys.executable, [sys.executable, str(helper.resolve()), *sys.argv[1:]])
'''
    module = os.path.relpath(PROJECT / "agents/pi.ts", extension.parent)
    if not module.startswith(("../", "./")):
        module = "./" + module
    adapter = "// Generated by the Herdr App hibernation installer.\n"
    adapter += f"export {{ default }} from {json.dumps(module)};\n"
    return {command: (launcher.encode(), 0o755, "herdr-hibernate"),
            extension: (adapter.encode(), 0o644, "agents/pi.ts")}


def check_entrypoints(files):
    for path, (content, _, source) in files.items():
        if path.is_symlink():
            if path.resolve() in {PROJECT / source, LEGACY_PROJECT.resolve() / source}:
                continue
        elif not path.exists() or (path.is_file() and path.read_bytes() == content):
            continue
        raise Error(f"Refusing to replace {path}")


def install_entrypoints(files):
    check_entrypoints(files)
    for path, (content, mode, _) in files.items():
        if not path.is_symlink() and path.exists() and path.stat().st_mode & 0o777 == mode:
            continue
        path.parent.mkdir(mode=0o700, exist_ok=True, parents=True)
        fd, temporary = tempfile.mkstemp(prefix=".install-", dir=path.parent)
        try:
            with os.fdopen(fd, "wb") as stream:
                stream.write(content)
                os.fchmod(stream.fileno(), mode)
            os.replace(temporary, path)
        finally:
            Path(temporary).unlink(missing_ok=True)


def systemd_value(text):
    # systemd expands specifiers and ExecStart performs environment expansion.
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("$", "$$") + '"'


def plan():
    hooks_path = CODEX_HOME / "hooks.json"
    hooks = read_json(hooks_path, {})
    session_start = hooks.setdefault("hooks", {}).setdefault("SessionStart", [])
    hook = {"type": "command", "command": f"{shlex.quote(str(COMMAND))} hook codex", "timeout": 20}
    if not any(hook["command"] == entry.get("command")
               for group in session_start for entry in group.get("hooks", [])):
        # Append so the trust indexes of existing hooks stay the same.
        session_start.append({"hooks": [hook]})

    programs = {name: shutil.which(name) for name in ("hc", "pi", "codex")}
    missing = [name for name, path in programs.items() if not path]
    if missing:
        raise Error("Install the required executables: " + ", ".join(missing))

    service = (
        "[Unit]\nDescription=Herdr App workspace hibernation and agent resume\n"
        "\n"
        "[Service]\nType=simple\n"
        f"Environment={systemd_value('HERDR_HIBERNATE_HC=' + programs['hc'])}\n"
        f"Environment={systemd_value('HERDR_HIBERNATE_STATE=' + str(STATE))}\n"
        f"Environment={systemd_value('HERDR_APP_HOME=' + str(APP_HOME))}\n"
        f"ExecStart={systemd_value(sys.executable)} {systemd_value(str(COMMAND))} serve\n"
        "UnsetEnvironment=HC_SESSION HC_SOCKET HC_TERMINAL_ID HC_TERMINAL_SOCKET\n"
        "KillMode=process\nRestart=on-failure\nRestartSec=2\n\n"
        "[Install]\nWantedBy=default.target\n"
    )
    if SERVICE.exists() and SERVICE.read_text() != service:
        raise Error(f"Refusing to replace a different service at {SERVICE}")

    return {hooks_path: hooks, STATE / "programs.json": programs}, service


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true")
    scope = parser.add_mutually_exclusive_group()
    scope.add_argument("--app-only", action="store_true", help="Update just the app mods and keys")
    scope.add_argument("--entrypoints-only", action="store_true", help="Install only the CLI and Pi entry points")
    args = parser.parse_args()
    files = {} if args.app_only else entrypoint_files()
    check_entrypoints(files)
    if args.entrypoints_only:
        for path in files:
            print(path)
        if args.apply:
            install_entrypoints(files)
        return
    keys_path, keys, mods = plan_app_ui()
    edits, service = ({}, None) if args.app_only else plan()
    for path in [keys_path, *mods, *edits, *files, *([SERVICE] if service else [])]:
        print(path)
    if not args.apply:
        return
    backup = STATE / "backups" / datetime.now().strftime("%Y%m%d-%H%M%S-%f")
    apply_app_ui(keys_path, keys, mods, backup)
    for path, value in edits.items():
        old = read_json(path)
        if old != value:
            if old is not None:
                save_json(backup / path.name, old)
            save_json(path, value)
    install_entrypoints(files)
    if service:
        SERVICE.parent.mkdir(exist_ok=True, parents=True)
        if not SERVICE.exists():
            SERVICE.write_text(service)
        subprocess.run(["systemd-analyze", "--user", "verify", SERVICE], check=True)
        subprocess.run(["systemctl", "--user", "daemon-reload"], check=True)
        subprocess.run(["systemctl", "--user", "enable", "--now", SERVICE.name], check=True)
    print(f"Previous JSON configuration, when changed, was saved under {backup}")


if __name__ == "__main__":
    try:
        main()
    except (Error, OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"herdr-hibernate install: {error}", file=sys.stderr)
        sys.exit(1)
